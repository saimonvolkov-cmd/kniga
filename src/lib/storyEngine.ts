const AGE_WORD_LIMIT: Record<BookInput["child"]["age_group"], number> = {
  "2-3": 14, "4-5": 22, "6-7": 30, "8-9": 30,
};

/* ── Narrative Module (демо-движок, полностью локальный) ────────────────── */
export function generateStory(input: BookInput, seed: number): StoryJSON {
  const rnd = mulberry32(seed);
  const n = input.child.name.trim() || "Малыш";
  const g = input.child.gender;
  const bank = GENRE_BANKS[input.genre];
  const compName = input.companion.name;
  const compRole = input.companion.role ?? "cheerleader";
  const themeId = input.story_theme === "surprise_me" ? pick(rnd, REAL_THEMES) : input.story_theme;
  const theme = THEMES[themeId as Exclude<StoryTheme, "surprise_me">];
  const limit = AGE_WORD_LIMIT[input.child.age_group];
  const N = input.spread_count;

  /* карта героя */
  const trialIdx = Array.from({ length: N - 8 }, (_, i) => i + 5);
  const hero_journey_map: Record<Stage, number[]> = {
    ordinary_world: [1, 2],
    call_to_adventure: [3, 4],
    trial: trialIdx,
    climax: [N - 3, N - 2],
    return_lesson: [N - 1, N],
  };

  const chars: Array<"child" | "companion"> = compName ? ["child", "companion"] : ["child"];
  const title = pick(rnd, bank.titles).split("{name}").join(n);

  const spreads: Spread[] = [];
  const push = (
    spread_number: number, stage: Stage, text: string, scene_description: string,
    gaze_direction: string, emotion: string
  ) =>
    spreads.push({
      spread_number, stage,
      text: trimToWords(text, limit),
      scene_description, gaze_direction, emotion,
      characters_present: chars,
    });

  /* 1 — обычный мир */
  const place = input.personal_details.favorite_place;
  const activity = input.personal_details.favorite_activity;
  push(1, "ordinary_world",
    `Жил(а)-был(а) ${n} — ${gf(g, "самый любопытный мальчик", "самая любопытная девочка")} на свете, ${bank.world}. Больше всего на свете ${n} ${activity ? `любил(а) ${activity}` : gf(g, "любил придумывать приключения", "любила придумывать приключения")}.`,
    `${bank.homeScene}; ребёнок сидит у окна и мечтательно смотрит вдаль`,
    "в окно на просыпающийся мир", "спокойствие");

  /* 2 — спутник / намёк темы */
  push(2, "ordinary_world",
    compName
      ? `А рядом всегда был(а) ${compName} — ${gf(g, "верный друг", "верная подруга")}. Вместе они могли всё-всё-всё. Ну, почти всё.`
      : `У ${n} была мечта — настоящее приключение. ${gf(g, "Он", "Она")} ${gf(g, "держал", "держала")} её под подушкой, чтобы не растерять по дороге.`,
    compName
      ? `${bank.homeScene}; ребёнок и маленький спутник сидят рядом на ковре и рассматривают что-то блестящее`
      : `${bank.homeScene}; ребёнок обнимает подушку, из-под подушки пробивается тёплый свет`,
    compName ? "на спутника рядом" : "на тёплый свет из-под подушки", "нежность");

  /* 3-4 — зов */
  const call = pick(rnd, bank.calls);
  push(3, "call_to_adventure", call.t(n, g),
    `${bank.env}; ${call.scene}`, call.gaze, "удивление");
  push(4, "call_to_adventure",
    compName
      ? `— В путь! — ${gf(g, "скомандовал", "скомандовала")} ${n}. ${compName} ${gf(g, "подпрыгнул", "подпрыгнула")} от радости, и приключение началось.`
      : `— В путь! — ${gf(g, "скомандовал", "скомандовала")} ${n}, ${gf(g, "надел", "надела")} самый смелый ботинок, и приключение началось.`,
    `${bank.env}; ребёнок решительно шагает по тропинке с котомкой, спина прямая, взгляд вперёд`,
    "вперёд на начинающуюся дорогу", "решимость");

  /* 5..N-4 — испытания */
  const obstacles = [...bank.obstacles];
  for (let i = obstacles.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [obstacles[i], obstacles[j]] = [obstacles[j], obstacles[i]];
  }
  const solutions = [...bank.solutions].sort(() => rnd() - 0.5);
  trialIdx.forEach((num, i) => {
    const ob = obstacles[i % obstacles.length];
    const sol = solutions[i % solutions.length];
    let text = `${ob.t} ${sol.t(n, g)}`;
    if (compName && i % 2 === 1) text += " " + companionLine(compRole, compName, n);
    if (activity && i === 2) text += ` Очень пригодилось то, что ${n} так ${gf(g, "любил", "любила")} ${activity}.`;
    if (place && i === trialIdx.length - 1) text += ` ${n} ${gf(g, "вспомнил", "вспомнила")} про ${place} — и сразу стало теплее.`;
    push(num, "trial", text,
      `${bank.env}; ${ob.scene}; ${sol.scene}`,
      ob.gaze, ob.emotion);
  });

  /* кульминация */
  push(N - 3, "climax", theme.climax.fear(n, g) + (compName ? ` Даже ${compName} притих(ла) и ${gf(g, "взял", "взяла")} ${n} за руку.` : ""),
    `${bank.env}; всё вокруг замерло и потемнело, ребёнок стоит в самом центре, сжав кулачки`,
    "на замерший мир вокруг", "волнение");
  push(N - 2, "climax", theme.climax.beat(n, g, compName),
    `${bank.env}; ${theme.climax.scene}`, theme.climax.gaze, "восторг");

  /* возвращение и урок */
  push(N - 1, "return_lesson",
    `Домой ${n} ${gf(g, "возвращался", "возвращалась")} ${gf(g, "уставший", "уставшая")}, но ${gf(g, "счастливый", "счастливая")}. Звёзды выстроились в дорожку, а ${place ? `впереди уже ждало ${place}` : "впереди уже ждал тёплый дом"}.`,
    `${bank.env}; ребёнок со спутником идёт по светящейся дорожке к домику, из окон льётся тёплый свет`,
    "на свет в окнах родного дома", "умиротворение");
  push(N, "return_lesson",
    `${theme.returnLine(n, g)} А ${theme.lesson} ${n} ${gf(g, "запомнил", "запомнила")} навсегда. Спокойной ночи, ${n}. До завтра!`,
    `${bank.homeScene}; ребёнок спит с улыбкой, спутник свернулся рядом, на подоконнике мерцает звёздочка`,
    "закрытые глаза, мирный сон", "нежность");

  const word_limit_per_spread = 30;

  return {
    title,
    word_limit_per_spread,
    cover: { scene_description: bank.cover(n, g, compName), title_text: title },
    back_cover: {
      scene_description: `мягкий декоративный орнамент в палитре книги: звёзды, листики и волны, без сложных действий и персонажей крупным планом`,
      blurb_text: theme.blurb(n),
    },
    hero_journey_map,
    spreads,
  };
}

/** Валидация Story JSON после реального API (Claude) */
export function validateStory(story: StoryJSON, expectedSpreads: number): boolean {
  if (!story || typeof story.title !== "string") return false;
  if (!Array.isArray(story.spreads) || story.spreads.length !== expectedSpreads) return false;
  return story.spreads.every(
    (s) =>
      typeof s.text === "string" && wordCount(s.text) > 0 &&
      typeof s.scene_description === "string" &&
      ["ordinary_world", "call_to_adventure", "trial", "climax", "return_lesson"].includes(s.stage)
  );
}

