/* ── сборка Story JSON ──────────────────────────────────────────────────── */
function journeyMap(n: number): Record<Stage, number[]> {
  const rng = (a: number, b: number) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
  return {
    ordinary_world: rng(1, 2),
    call_to_adventure: rng(3, 4),
    trial: rng(5, n - 4),
    climax: rng(n - 3, n - 2),
    return_lesson: rng(n - 1, n),
  };
}

const stageFor = (map: Record<Stage, number[]>, num: number): Stage =>
  (Object.keys(map) as Stage[]).find((s) => map[s].includes(num)) ?? "trial";

