/* ── Спутник: реплики по роли (настоящее время — род не нужен) ──────────── */
export function companionLine(role: CompanionRole, comp: string, childName: string): string {
  switch (role) {
    case "protector":
      return `${comp} идёт впереди всех, хвост трубой: с таким защитником путь безопасен.`;
    case "joker":
      return `${comp} смешно чихает — и все преграды прыскают со смеху и расступаются.`;
    case "advisor":
      return `${comp} шепчет на ушко мудрый совет — и сразу понятно, что делать дальше.`;
    case "cheerleader":
      return `«Ты сможешь, ${childName}!» — подбадривает ${comp}, и сил прибавляется вдвое.`;
  }
}

